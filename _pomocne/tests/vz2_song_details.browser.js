'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require('playwright');
module.exports = async ({ base, clients, request, good, check, song, empty, rehearsal, read }) => {
    const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || '/usr/bin/chromium' });
    const screenshots = path.resolve(__dirname, '../dist/vz2.1.1'); fs.mkdirSync(screenshots, { recursive: true });
    try {
        const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
        const [name, value] = clients.alice.cookie.split('='); await context.addCookies([{ name, value, url: base }]);
        const page = await context.newPage(), errors = [];
        page.on('pageerror', e => errors.push(e.message)); page.on('dialog', d => d.accept());
        await page.goto(base + 'index.php?v=2&kind=song&collection_id=' + song.id);
        const header = page.locator('#song-details'), editor = page.locator('.song-details-dialog');
        await header.locator('.song-details-edit').waitFor();
        assert.match(await header.textContent(), /120\/132,5\/120 BPM · 4\/4 \+ 3\/4 \+ 4\/4/);
        assert.equal(await header.locator('img').count(), 0, 'description is plain text');
        await header.locator('.song-details-edit').click();
        await editor.locator('[name=tempos]').fill('124 / 132,5 / 124');
        await editor.locator('[name=meters]').fill('4/4');
        await editor.getByRole('button', { name: 'Přidat takt', exact: true }).click();
        await editor.getByRole('option', { name: '6/8', exact: true }).click();
        assert.equal(await editor.locator('[name=meters]').inputValue(), '4/4 + 6/8');
        assert.equal(await editor.locator('select').count(), 0);
        const description = 'Po druhém refrénu zrychlit, pak se vrátit.\n' + 'Dohodnuté poznámky ke skladbě a společný závěr. '.repeat(12) + '\n<img src=x>';
        await editor.locator('[name=description]').fill(description);
        await editor.getByRole('button', { name: 'Uložit', exact: true }).click();
        await editor.waitFor({ state: 'hidden' });
        await header.locator('.song-details-description').filter({ hasText: 'Dohodnuté' }).waitFor();
        assert.deepEqual((await read()).song_tempos, [124,132.5,124]);
        assert.deepEqual((await read()).song_meters, ['4/4','6/8']);
        await header.locator('.song-details-more').waitFor({ state: 'visible' });
        const collapsedHeight = (await header.locator('p').boundingBox()).height;
        await header.locator('.song-details-more').click();
        assert((await header.locator('p').boundingBox()).height > collapsedHeight);
        await header.locator('.song-details-more').click();
        await page.locator('#catalog-picker').click();
        assert.equal(await page.locator('.collection-bpm').filter({ hasText: '124/132,5/124' }).count(), 1);
        await page.locator('#catalog-close').click();
        await header.locator('.song-details-edit').click();
        await editor.locator('[name=description]').fill('Rozepsaný společný popisek');
        const current = await read();
        await good('admin', { action: 'song_details_update', id: song.id, revision: Number(current.revision), song_tempos: [140], song_meters: ['7/8'], song_description: 'Změna v druhém okně' });
        await editor.getByRole('button', { name: 'Uložit', exact: true }).click();
        await editor.locator('.song-details-reload').waitFor({ state: 'visible' });
        await editor.locator('.song-details-reload').click();
        await editor.locator('.song-details-comparison').filter({ hasText: 'Změna v druhém okně' }).waitFor();
        assert.equal(await editor.locator('[name=description]').inputValue(), 'Rozepsaný společný popisek');
        await editor.locator('.song-details-rebase').click();
        await page.route('**/php/ajax/vz2.php', route => route.request().method() === 'POST' ? route.abort() : route.continue());
        await editor.getByRole('button', { name: 'Uložit', exact: true }).click();
        await editor.locator('.error').filter({ hasText: /fetch/i }).waitFor();
        assert.equal(await editor.locator('[name=description]').inputValue(), 'Rozepsaný společný popisek');
        await page.unroute('**/php/ajax/vz2.php');
        await editor.locator('[name=description]').fill(description);
        await editor.getByRole('button', { name: 'Uložit', exact: true }).click();
        await editor.waitFor({ state: 'hidden' });
        await header.locator('.song-details-music').filter({ hasText: '124' }).waitFor();
        for (const width of [320,390,1440]) {
            await page.setViewportSize({ width, height: 844 });
            await header.locator('.song-details-music').waitFor({ state: 'visible' });
            assert(await header.locator('.song-details-music').isVisible(), 'metadata visible at ' + width);
            assert.equal(await page.locator('#car-mode-collection-open').count(), 0);
            assert.equal(await page.locator('#catalog-picker').isVisible(), width < 1200);
            if (width < 768) {
                const checkRows = async () => {
                    const boxes = await page.evaluate(() => {
                        const rect = selector => { const r = document.querySelector(selector).getBoundingClientRect(); return { left: r.left, right: r.right, top: r.top, bottom: r.bottom, center: (r.top + r.bottom) / 2 }; };
                        return { picker: rect('#catalog-picker'), fullscreen: rect('#panel-recordings .panel-fullscreen-button'), music: rect('.song-details-line'), upload: rect('#upload-open') };
                    });
                    assert(Math.abs(boxes.picker.center - boxes.fullscreen.center) < 2, 'picker and fullscreen share the top row');
                    assert(boxes.picker.right <= boxes.fullscreen.left, 'top controls do not overlap');
                    assert(Math.abs(boxes.music.center - boxes.upload.center) < 2, 'metadata and upload share the second row');
                    assert(boxes.music.right <= boxes.upload.left, 'second-row controls do not overlap');
                    assert(boxes.music.top >= boxes.picker.bottom, 'metadata follows picker');
                };
                await checkRows();
                await page.locator('#panel-recordings .panel-fullscreen-button').click();
                assert(await page.locator('#panel-recordings').evaluate(e => e.classList.contains('panel-fullscreen')));
                await checkRows();
                await page.locator('#panel-recordings .panel-fullscreen-button').click();
                await page.locator('[data-mobile-panel=lyrics]').click();
                await header.locator('.song-details-music').waitFor({ state: 'visible' });
                await page.locator('[data-mobile-panel=recordings]').click();
                await checkRows();
            }
            assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
            await page.screenshot({ path: path.join(screenshots, 'song-' + width + '.png') });
            await header.locator('.song-details-edit').click();
            const box = await editor.boundingBox(); assert(box.x >= 0 && box.x + box.width <= width + 1);
            await page.screenshot({ path: path.join(screenshots, 'editor-' + width + '.png') });
            await editor.getByRole('button', { name: 'Zavřít popisek' }).click();
            await editor.waitFor({ state: 'hidden' });
        }
        check(true, 'browser: mobile/desktop song metadata, custom meter menu, BPM badge, expansion, safe text, conflict and network retry');
        await page.goto(base + 'index.php?v=2&kind=rehearsal&collection_id=' + rehearsal.id);
        await page.locator('#collection-title-name').filter({ hasText: 'Zkouška' }).waitFor({ state: 'attached' });
        assert(await header.isHidden());
        await page.goto(base + 'prehled.php');
        const preset = page.locator('[data-overview-preset=song_details]'), filters = page.locator('#overview-filters');
        assert(await preset.isVisible()); assert.equal(await filters.evaluate(e => e.open), false);
        await preset.click();
        assert.equal(await preset.getAttribute('aria-pressed'), 'true');
        assert.equal(await page.locator('.overview-collection').count(), 0, 'preset does not load data until generate');
        await page.getByRole('button', { name: 'Vytvořit výpis' }).click();
        await page.locator('.overview-song-details').waitFor();
        assert.equal(await page.locator('.overview-entry').count(), 1);
        assert.match(await page.locator('.overview-song-details').textContent(), /124 \/ 132,5 \/ 124 BPM · 4\/4 \+ 6\/8/);
        assert.match(await page.locator('.overview-song-details').textContent(), /Dohodnuté/);
        assert.equal(await page.locator('.overview-song-details img').count(), 0);
        assert(await page.locator('#overview-rehearsals').isHidden());
        await filters.locator('summary').click();
        await page.locator('[data-collection-id="' + song.id + '"]').uncheck();
        assert.equal(await page.locator('#overview-preset-status').textContent(), 'Vlastní');
        await preset.click();
        assert.equal(await page.locator('.overview-song-details').count(), 0, 'preset preserves individual selection');
        await filters.locator('summary').click();
        await page.locator('[data-collection-id="' + song.id + '"]').check();
        await preset.click();
        for (const width of [320,390,1440]) {
            await page.setViewportSize({ width, height: 844 });
            assert(await preset.isVisible());
            assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
            await page.screenshot({ path: path.join(screenshots, 'overview-' + width + '.png'), fullPage: true });
        }
        await page.locator('[data-overview-preset=lyrics]').click();
        assert.equal(await page.locator('.overview-song-details').count(), 0);
        assert.match(await page.locator('.overview-entry').textContent(), /Text pouze pro jinou předvolbu/);
        await page.locator('[data-overview-preset=all]').click();
        assert.equal(await page.locator('.overview-song-details').count(), 1);
        assert.equal(await filters.evaluate(e => e.open), false);
        await page.reload(); assert.equal(await filters.evaluate(e => e.open), false);
        check(true, 'browser: visible presets, default collapsed custom controls, dedicated song details preset, preserved selection and responsive overview');
        const guestContext = await browser.newContext();
        const [guestName, guestValue] = clients.guest.cookie.split('='); await guestContext.addCookies([{ name: guestName, value: guestValue, url: base }]);
        const guestPage = await guestContext.newPage();
        await guestPage.goto(base + 'index.php?v=2&kind=song&collection_id=' + song.id);
        await guestPage.locator('#song-details .song-details-music').waitFor();
        assert.equal(await guestPage.locator('.song-details-edit').count(), 0);
        assert.deepEqual(errors, []);
        check(true, 'browser: guest reads song metadata without edit controls; rehearsal header stays unchanged');
    } finally { await browser.close(); }
};
