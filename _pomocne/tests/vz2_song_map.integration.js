'use strict';
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
module.exports = async ({ request, clients, good, db, check }) => {
    const song = await good('admin', { action: 'collection_create', kind: 'song', title: 'Mapa — datový základ' });
    const rehearsal = await good('admin', { action: 'collection_create', kind: 'rehearsal', title: 'Mapa není zkouška' });
    const endpoint = 'php/ajax/vz2_content.php';
    const query = { action: 'document', kind: 'song_map', collection_id: song.id };
    const get = (who, fields = query) => request(clients[who], endpoint + '?' + new URLSearchParams(fields));
    const post = (who, fields, options) => request(clients[who], endpoint, fields, options);
    const map = { schema_version: 1, sections: [{ id: 'a'.repeat(32), name: 'Sloka 1', bars: [{ id: 'b'.repeat(32), base: 'ride', fill: 2, crash: false, special: null, detail: '  RD | x-x-x-x-\nPoznámka <script>\n' }] }] };
    const save = { action: 'document_save', kind: 'song_map', collection_id: song.id, document_id: null, current_revision: 0, body: JSON.stringify(map) };
    assert.equal((await get('anon')).status, 401);
    assert.equal((await get('guest')).json().document, null);
    assert.equal((await get('guest')).json().can_edit, false);
    assert.equal((await post('guest', save)).status, 403);
    assert.equal((await post('alice', save, { noCsrf: true })).status, 403);
    assert.equal((await get('admin', { ...query, collection_id: rehearsal.id })).status, 400);
    assert.equal((await post('admin', { ...save, collection_id: rehearsal.id })).status, 400);
    assert.equal((await post('admin', { ...save, body: '{"schema_version":1,"sections":{}}' })).status, 400);
    const race = await Promise.all(['alice', 'bob'].map(who => post(who, save)));
    assert.deepEqual(race.map(r => r.status).sort(), [200, 409]);
    const first = (await get('guest')).json(); const id = first.document.id;
    assert.deepEqual(JSON.parse(first.version.body), map);
    const update = { ...save, document_id: id, current_revision: 1 };
    map.sections[0].bars[0].detail = 'nezávislá druhá verze';
    const second = await post('bob', { ...update, body: JSON.stringify(map), created_by: 1 });
    assert.equal(second.status, 200, second.text);
    assert.equal(second.json().version.created_by, 3);
    assert.equal((await post('alice', update)).status, 409);
    const old = (await get('guest', { ...query, revision: 1 })).json();
    assert.equal(JSON.parse(old.version.body).sections[0].bars[0].detail, '  RD | x-x-x-x-\nPoznámka <script>\n');
    const restored = await post('alice', { ...update, action: 'document_restore', current_revision: 2, source_revision: 1 });
    assert.equal(restored.status, 200, restored.text);
    assert.equal(restored.json().document.current_revision, 3);
    assert.equal(restored.json().version.body, old.version.body);
    const history = (await get('guest', { ...query, action: 'history' })).json();
    assert.deepEqual(history.versions.map(v => Number(v.revision)), [3, 2, 1]);
    assert(history.versions.every(v => v.author && v.created_at.endsWith('Z')));
    db("CREATE TRIGGER reject_map_audit BEFORE INSERT ON vz2_activity_log FOR EACH ROW BEGIN IF NEW.action='document.version_created' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='test map audit failure'; END IF; END");
    try { assert.equal((await post('alice', { ...update, current_revision: 3 })).status, 500); }
    finally { db('DROP TRIGGER reject_map_audit'); }
    assert.equal((await get('guest')).json().document.current_revision, 3);
    assert.equal(db('SELECT * FROM vz2_document_versions WHERE document_id=?', [id]).length, 3);
    check(true, 'song map: song scope, identity/CSRF, first-save race, immutable snapshots, authors, restore, history and atomic audit rollback');
    await good('admin', { action: 'collection_rename', id: song.id, revision: 1, title: 'Mapa — přejmenovaná skladba' });
    assert.equal((await get('guest')).json().document.id, id);
    assert.equal((await get('guest')).json().document.current_revision, 3);
    await good('admin', { action: 'delete_collection', id: song.id, revision: 2, confirm: 'Mapa — přejmenovaná skladba', request_key: crypto.randomBytes(16).toString('hex') });
    assert.equal(db('SELECT * FROM vz2_document_versions WHERE document_id=?', [id]).length, 0);
    assert(db("SELECT * FROM vz2_activity_log WHERE target_type='document' AND target_id=?", [id]).length >= 3);
    await good('admin', { action: 'delete_collection', id: rehearsal.id, revision: 1, confirm: 'Mapa není zkouška', request_key: crypto.randomBytes(16).toString('hex') });
    check(true, 'song map identity survives song rename; existing parent deletion removes snapshots but retains their audit; fixtures cleaned');
};
