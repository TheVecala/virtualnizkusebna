'use strict';
const assert = require('node:assert/strict');
module.exports = async function ({ request, clients, good, upload, wav, db, check }) {
    const song = await good('alice', { action: 'collection_create', kind: 'song', title: 'Interval song A' });
    const other = await good('alice', { action: 'collection_create', kind: 'song', title: 'Interval song B' });
    const rehearsal = await good('alice', { action: 'collection_create', kind: 'rehearsal', title: 'Interval rehearsal' });
    const audio = await upload('alice', rehearsal.id, 'Interval source', 'single', ['take.wav'], [wav(10)]);
    assert.equal(audio.status, 201, audio.text); const recording_id = audio.json().id;
    const endpoint = 'php/ajax/vz2_timestamps.php';
    const read = async () => (await request(clients.alice, endpoint + '?recording_id=' + recording_id)).json();
    const save = async (fields, who = 'alice', status = null) => {
        const list = await read();
        const row = fields.id ? list.entries.find(e => e.id === fields.id) : null;
        const result = await request(clients[who], endpoint, { recording_id, timestamps_revision: list.timestamps_revision, ...(row ? { revision: row.revision } : {}), ...fields });
        assert.equal(result.status, status ?? (fields.id ? 200 : 201), result.text);
        return result.json();
    };
    const interval = { action: 'save_interval', kind: 'song_start', time_ms: 123, end_time_ms: null, body: '', song_collection_id: song.id };
    let list = await save(interval), take = list.annotations[0];
    assert.equal(take.status, 'open'); assert.equal(take.song_id, song.id);
    assert.equal(db('SELECT id FROM vz2_rehearsal_plays WHERE source_recording_id=?', [recording_id]).length, 0);
    list = await save({ ...interval, id: take.timestamp_id, end_time_ms: 9123 });
    take = list.annotations.find(i => i.id === take.id);
    let history = db('SELECT * FROM vz2_rehearsal_plays WHERE source_recording_id=?', [recording_id]);
    assert.equal(history.length, 1); const historyId = history[0].id;
    assert.equal(history[0].song_collection_id, song.id);
    list = await save({ ...interval, id: take.timestamp_id, end_time_ms: 9123, song_collection_id: other.id, body: 'Pokus přejmenovaný' });
    assert.equal(db('SELECT id FROM vz2_rehearsal_plays WHERE source_recording_id=?', [recording_id])[0].id, historyId);
    assert.equal(db('SELECT song_collection_id FROM vz2_rehearsal_plays WHERE id=?', [historyId])[0].song_collection_id, other.id);
    check(true, 'intervals: assignment survives an open take; completion and reassignment update one history row atomically');
    const passage = { action: 'save_interval', kind: 'passage', time_ms: 1001, end_time_ms: 2507, passage_type: 'chorus', body: '', note_text: 'Nástup hlasu', parent_timestamp_id: take.timestamp_id };
    list = await save(passage); const chorus = list.annotations.find(i => i.kind === 'passage');
    assert.equal(chorus.label, 'Refrén'); assert.equal(chorus.song_id, other.id); assert.equal(chorus.end_ms, 2507);
    list = await save({ action: 'create', kind: 'passage', time_ms: 3000, body: 'Legacy passage' });
    const legacy = list.annotations.find(i => i.label === 'Legacy passage');
    assert.equal(legacy.status, 'open'); assert.equal(legacy.end_ms, null);
    await save({ ...passage, time_ms: 1200, end_time_ms: 2700, parent_timestamp_id: null, body: 'Překryv' });
    const snapshot = JSON.stringify(await read());
    await save({ ...interval, id: take.timestamp_id, song_collection_id: other.id, end_time_ms: 2000 }, 'alice', 400);
    assert.equal(JSON.stringify(await read()), snapshot, 'failed parent resize rolls back metadata and revision');
    for (const end_time_ms of [1001, 0, 10001, 1.1, '2500', true]) await save({ ...passage, end_time_ms }, 'alice', 400);
    await save({ ...passage, passage_type: [] }, 'alice', 400);
    await save({ ...passage, parent_timestamp_id: chorus.timestamp_id }, 'alice', 400);
    await save({ ...passage, id: chorus.timestamp_id }, 'bob', 403);
    const foreign = await upload('alice', rehearsal.id, 'Other source', 'single', ['foreign.wav'], [wav(10)]);
    const badParent = await request(clients.alice, endpoint, { ...passage, recording_id: foreign.json().id, timestamps_revision: 1 });
    assert.equal(badParent.status, 400, badParent.text);
    check(true, 'intervals: explicit passage end, presets, notes, overlap and legacy data; invalid bounds/parents and foreign edits rejected');
    const before = await read();
    const results = await Promise.all(['A', 'B'].map(body => request(clients.alice, endpoint, { ...passage, body, recording_id, timestamps_revision: before.timestamps_revision })));
    assert.deepEqual(results.map(r => r.status).sort(), [201, 409]);
    const saved = JSON.stringify(await read());
    db("CREATE TRIGGER reject_interval_audit BEFORE INSERT ON vz2_activity_log FOR EACH ROW BEGIN IF NEW.action LIKE 'timestamp.%' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='test'; END IF; END");
    try { await save({ ...interval, id: take.timestamp_id, end_time_ms: 9000, song_collection_id: song.id }, 'alice', 500); }
    finally { db('DROP TRIGGER reject_interval_audit'); }
    assert.equal(JSON.stringify(await read()), saved);
    assert.equal(db('SELECT song_collection_id FROM vz2_rehearsal_plays WHERE id=?', [historyId])[0].song_collection_id, other.id);
    check(true, 'intervals: concurrent saves conflict; audit failure rolls back both boundaries, assignment and history');
    list = await read(); const end = list.entries.find(e => e.id === take.end_timestamp_id);
    const invalidBoundary = await save({ action: 'update', id: end.id, kind: 'note', time_ms: end.time_ms, body: 'Invalid conversion' }, 'alice', 409);
    assert(invalidBoundary.error);
    const catalog = (await request(clients.alice, 'php/ajax/vz2.php?action=catalog')).json();
    assert.deepEqual(catalog.recordings.find(r => r.id === recording_id).annotations, (await read()).annotations);
    const exported = await request(clients.alice, endpoint + '?action=export&recording_id=' + recording_id);
    assert(exported.text.includes('00:01 – 00:02')); assert(exported.text.includes('Doplnit konec')); assert(exported.text.includes('Nástup hlasu'));
    const historyRow = db('SELECT * FROM vz2_rehearsal_plays WHERE id=?', [historyId])[0];
    const removed = await request(clients.alice, 'php/ajax/vz2_history.php', { action: 'delete', id: historyId, revision: historyRow.revision });
    assert.equal(removed.status, 200, removed.text);
    list = await read(); assert.equal(list.annotations.find(i => i.id === take.id).song_id, null);
    await save({ action: 'update', id: take.timestamp_id, kind: 'song_start', time_ms: 123, body: 'Still unassigned' });
    assert.equal(db('SELECT id FROM vz2_rehearsal_plays WHERE source_recording_id=?', [recording_id]).length, 0);
    await save({ action: 'delete_interval', id: take.timestamp_id }, 'alice', 409);
    list = await read();
    const recording = db('SELECT * FROM vz2_recordings WHERE id=?', [recording_id])[0];
    await good('alice', { action: 'remove_audio', id: recording_id, revision: recording.revision, confirm: recording.title, request_key: require('node:crypto').randomBytes(16).toString('hex') });
    list = await save({ ...passage, id: chorus.timestamp_id, end_time_ms: 2600 });
    assert.equal(list.duration_ms, 10000); assert.equal(list.annotations.find(i => i.id === chorus.id).end_ms, 2600);
    check(true, 'intervals: catalogue/export agree, history removal clears assignment, referenced parents protected, editing works without audio');
    const duplicate = { ...interval, body: 'Ke smazání', song_collection_id: null, end_time_ms: 500 };
    list = await save(duplicate);
    const disposable = list.annotations.find(i => i.label === 'Ke smazání');
    list = await save({ action: 'delete_interval', id: disposable.timestamp_id });
    assert(!list.entries.some(e => [disposable.timestamp_id, disposable.end_timestamp_id].includes(e.id)), 'whole interval deletion removes both boundaries');
    await save({ ...duplicate, id: 0 }, 'alice', 400);
    await save(duplicate, 'guest', 403);
    const latest = await read();
    const noCsrf = await request(clients.alice, endpoint, { ...duplicate, recording_id, timestamps_revision: latest.timestamps_revision }, { noCsrf: true });
    assert.equal(noCsrf.status, 403);
    list = await save(duplicate);
    const mixed = list.annotations.find(i => i.label === 'Ke smazání');
    db('UPDATE vz2_timestamps SET created_by=3 WHERE id=?', [mixed.end_timestamp_id]);
    const snapshotMixed = JSON.stringify(await read());
    await save({ ...duplicate, id: mixed.timestamp_id, end_time_ms: 600 }, 'alice', 403);
    assert.equal(JSON.stringify(await read()), snapshotMixed, 'foreign end ownership blocks both-boundary save atomically');
    await save({ action: 'delete_interval', id: mixed.timestamp_id }, 'admin');
    check(true, 'intervals: complete deletion, invalid IDs, guest/CSRF protection and ownership of both boundaries');
};
