'use strict';
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
module.exports = async function ({ base, clients, good, upload, wav, request, db, check, temp }) {
    const song = await good('admin', { action: 'collection_create', kind: 'song', title: 'Browser interval song' });
    const rehearsal = await good('admin', { action: 'collection_create', kind: 'rehearsal', title: 'Browser interval rehearsal' });
    const audio = await upload('admin', rehearsal.id, 'Browser intervals', 'single', ['interval.wav'], [wav(10)]);
    const mix = await upload('admin', rehearsal.id, 'Browser mix intervals', 'multitrack', ['left.wav', 'right.wav'], [wav(10), wav(10)]);
    assert.equal(audio.status, 201, audio.text); assert.equal(mix.status, 201, mix.text);
    const id = audio.json().id, mixId = mix.json().id, endpoint = 'php/ajax/vz2_timestamps.php';
    const read = async rid => (await request(clients.admin, endpoint + '?recording_id=' + rid)).json();
    const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH, args: ['--autoplay-policy=no-user-gesture-required'] });
    try {
        const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
        const [name, value] = clients.admin.cookie.split('=');
        await context.addCookies([{ name, value, url: base }]);
        const page = await context.newPage(), errors = [];
        page.on('pageerror', e => errors.push(e.message)); page.on('dialog', d => d.accept());
        await page.route('https://cdn.jsdelivr.net/**', route => route.abort());
        await page.goto(base + 'index.php?collection_id=' + rehearsal.id);
        const card = page.locator('#recording-' + id), panel = card.locator('.vz2-timestamps');
        await card.getByRole('button', { name: 'Otevřít časové značky', exact: true }).click();
        const editor = page.locator('.vz2-annotation-editor'), interval = page.locator('.vz2-interval-editor');
        const add = async (host, kind) => {
            await host.getByRole('button', { name: 'Přidat značku', exact: true }).click();
            await editor.getByRole('button', { name: kind, exact: true }).click();
            await interval.waitFor({ state: 'visible' });
        };
        const setTime = async (edge, value) => {
            await interval.locator('.annotation-fine').evaluate(e => e.open = true);
            await interval.locator('[name=' + edge + ']').fill(value);
            await interval.locator('[name=' + edge + ']').press('Tab');
        };
        const choose = async (name, value) => {
            await interval.locator('[data-choice=' + name + '] > button').click();
            await page.locator('.annotation-choice-popup:not([hidden]) [data-value="' + value + '"]').click();
        };
        const setNote = async value => {
            await interval.locator('.annotation-note-open').click();
            await page.locator('.annotation-note-dialog textarea').fill(value);
            await page.getByRole('button', { name: 'Hotovo', exact: true }).click();
        };
        const save = async () => { await interval.locator('.annotation-save').click(); await interval.waitFor({ state: 'hidden' }); };
        await add(panel, 'Pokus');
        await setTime('start', '00:01.123');
        await setTime('end', '00:08.456');
        await choose('song', String(song.id));
        await interval.locator('[name=label]').fill('Pokus 1');
        await save();
        assert.equal(await panel.locator('li.ts-song_start').count(), 1);
        assert.equal(await panel.locator('li.ts-song_end').count(), 0, 'paired boundaries are one item');
        assert.match(await panel.locator('li.ts-song_start').textContent(), /00:01 – 00:08/);
        let list = await read(id), take = list.annotations.find(i => i.kind === 'take');
        assert.deepEqual([take.start_ms, take.end_ms, take.song_id], [1123, 8456, song.id]);
        assert.equal(db('SELECT id FROM vz2_rehearsal_plays WHERE source_recording_id=?', [id]).length, 1);
        check(true, 'browser: one take editor saves exact start/end and song; list collapses pair and history is assigned');
        await add(panel, 'Pasáž');
        await setTime('start', '00:02.345');
        await setTime('end', '00:04.678');
        await choose('passage_type', 'chorus');
        await choose('parent', String(take.timestamp_id));
        await setNote('<img src=x onerror=alert(1)> Nástup');
        await save();
        let passage = panel.locator('.ts-passage').filter({ hasText: 'Nástup' });
        assert.equal(await passage.locator('img').count(), 0);
        assert.equal(await passage.locator('[data-playback=loop]').getAttribute('data-end-ms'), '4678');
        await passage.getByRole('button', { name: 'Upravit', exact: true }).click();
        await interval.locator('[name=label]').fill('Refrén 2');
        await save();
        list = await read(id); const chorus = list.annotations.find(i => i.label === 'Refrén 2');
        assert.deepEqual([chorus.start_ms, chorus.end_ms, chorus.passage_type, chorus.parent_id, chorus.song_id], [2345, 4678, 'chorus', take.id, song.id]);
        check(true, 'browser: passage preset, parent and note; safe rendering and unchanged millisecond precision on text edit');
        await add(panel, 'Pasáž');
        await setTime('start', '00:05');
        await interval.locator('[name=label]').fill('Otevřená pasáž');
        await choose('parent', String(take.timestamp_id));
        await save();
        const open = panel.locator('.ts-passage').filter({ hasText: 'Otevřená pasáž' });
        assert.match(await open.textContent(), /Doplnit konec/);
        assert.equal(await open.getByRole('button', { name: 'Smyčka', exact: true }).isDisabled(), true);
        await open.getByRole('button', { name: 'Ukončit pasáž' }).click();
        await setTime('end', '00:07');
        await save();
        assert(!/Doplnit konec/.test(await open.textContent()));
        await panel.locator('.ts-song_start').getByRole('button', { name: 'Upravit', exact: true }).click();
        await setTime('end', '00:03');
        await interval.locator('.annotation-save').click();
        await interval.locator('.error').filter({ hasText: 'Pasáž musí ležet' }).waitFor();
        await interval.getByRole('button', { name: 'Zrušit', exact: true }).click();
        assert.equal((await read(id)).annotations.find(i => i.id === take.id).end_ms, 8456);
        check(true, 'browser: open passage has no loop, explicit finish works, parent cannot silently clip children');
        passage = panel.locator('.ts-passage').filter({ hasText: 'Refrén 2' });
        await passage.getByRole('button', { name: 'Upravit', exact: true }).click();
        await setNote('Rozepsaná poznámka');
        list = await read(id); const row = list.entries.find(e => e.id === chorus.timestamp_id);
        const changed = await request(clients.admin, endpoint, { action: 'update', recording_id: id, timestamps_revision: list.timestamps_revision, id: row.id, revision: row.revision, kind: row.kind, time_ms: row.time_ms, body: 'Druhé okno' });
        assert.equal(changed.status, 200, changed.text);
        await interval.locator('.annotation-save').click();
        await interval.locator('.interval-reload').waitFor({ state: 'visible' });
        await interval.locator('.annotation-note-open').click();
        assert.equal(await page.locator('.annotation-note-dialog textarea').inputValue(), 'Rozepsaná poznámka');
        await page.getByRole('button', { name: 'Hotovo', exact: true }).click();
        await interval.locator('.interval-reload').click();
        await interval.locator('.interval-current').filter({ hasText: 'Druhé okno' }).waitFor();
        await interval.locator('.annotation-rebase').click();
        await save();
        check(true, 'browser: revision conflict preserves all draft fields and explicit comparison permits a retry');
        await page.setViewportSize({ width: 390, height: 844 });
        await passage.getByRole('button', { name: 'Upravit', exact: true }).click();
        await page.screenshot({ path: require('node:path').join(temp, 'mobile-interval.png') });
        const box = await interval.boundingBox(); assert(box.x >= 0 && box.x + box.width <= 391);
        await setTime('end', '00:04.900');
        await save();
        assert.equal((await read(id)).annotations.find(i => i.id === chorus.id).end_ms, 4900);
        check(true, 'browser: mobile interval editor fits viewport and edits the same interval');
        await page.setViewportSize({ width: 1440, height: 1000 });
        await card.getByRole('button', { name: 'Otevřít v Looperu', exact: true }).click();
        await page.waitForFunction(() => Vz2Player.getState()?.phase === 'ready' && !Vz2Player.getState().loading);
        await page.evaluate(() => Vz2Player.seek(2));
        const looperPanel = page.locator('#looper-timestamps');
        await looperPanel.locator('details').evaluate(e => e.open = true);
        await add(looperPanel, 'Pokus');
        await interval.locator('.annotation-wave-message').waitFor({ state: 'hidden' });
        await interval.getByRole('button', { name: 'Přehrát', exact: true }).click();
        await page.waitForFunction(() => Vz2Player.getState().playing);
        await interval.getByRole('button', { name: 'Pozastavit', exact: true }).click();
        const beforeSeek = await page.evaluate(() => Vz2Player.getState().position);
        await interval.getByRole('button', { name: 'Vpřed o 5 sekund' }).click();
        const afterSeek = await page.evaluate(() => Vz2Player.getState().position);
        assert(Math.abs(afterSeek - beforeSeek - 5) < .1);
        await interval.locator('[data-capture=end]').click();
        await interval.locator('.annotation-close').click();
        assert(Math.abs(await page.evaluate(() => Vz2Player.getState().position) - afterSeek) < .1, 'closing does not reset host playback position');
        check(true, 'browser: editor shows real Looper waveform, controls the same audio, captures end and preserves position');
        const mixCard = page.locator('#recording-' + mixId);
        await mixCard.locator('.recording-toggle').click();
        await mixCard.getByRole('button', { name: 'Otevřít v Mixéru', exact: true }).click();
        await page.waitForFunction(rid => window.MultitrackApp?.getState()?.id === String(rid) && window.MultitrackApp.getState().phase === 'ready', mixId);
        assert.deepEqual(errors, [], 'Mixer load errors');
        const mixPanel = page.locator('#mixer-timestamps');
        await mixPanel.locator('details').evaluate(e => e.open = true);
        await add(mixPanel, 'Pasáž');
        await interval.locator('.annotation-wave-message').waitFor({ state: 'hidden' });
        await interval.getByRole('button', { name: 'Přehrát', exact: true }).click();
        await page.waitForFunction(() => MultitrackApp.getState().playing);
        await interval.getByRole('button', { name: 'Pozastavit', exact: true }).click();
        assert.equal(await page.evaluate(() => MultitrackApp.getState().playing), false);
        check(true, 'browser: editor waveform and transport work with decoded multitrack audio');
        await setTime('start', '00:01'); await setTime('end', '00:03');
        await choose('passage_type', 'solo'); await save();
        const mixPassage = mixPanel.locator('.ts-passage');
        await mixPassage.getByRole('button', { name: 'Smyčka', exact: true }).click();
        assert.equal(await mixPanel.getByRole('button', { name: 'Vypnout smyčku' }).isVisible(), true);
        await mixPanel.getByRole('button', { name: 'Vypnout smyčku' }).click();
        assert.equal((await read(mixId)).annotations[0].end_ms, 3000);
        check(true, 'browser: Mixer uses the same passage editor and explicit loop range');
        await page.goto(base + 'useky.php?recording_id=' + id);
        await page.waitForFunction(() => !!window.Vz2TimestampModel && !!window.Vz2SegmentsModel);
        const segmentEnd = await page.evaluate(async rid => {
            const r = await (await fetch('php/ajax/vz2_timestamps.php?recording_id=' + rid)).json();
            return window.Vz2SegmentsModel.build(r).segments.find(i => i.kind === 'passage').end_ms;
        }, mixId);
        assert.equal(segmentEnd, 3000);
        assert.deepEqual(errors, []);
        check(true, 'browser: standalone segments page loads the common model and sees identical range');
        await page.locator('[data-segment-id="' + chorus.id + '"]').click();
        await page.locator('#segments-loop').check();
        await page.locator('#segments-play').click();
        await page.waitForFunction(() => !document.querySelector('#segments-audio').paused);
        await page.locator('#segments-edit').click();
        await interval.locator('[name=label]').fill('Úprava z časové osy');
        await save();
        assert.equal(await page.locator('#segments-selected-title').textContent(), 'Úprava z časové osy');
        assert.equal((await read(id)).annotations.find(i => i.id === chorus.id).label, 'Úprava z časové osy');
        assert.equal(await page.locator('#segments-audio').evaluate(a => a.paused), false);
        assert.equal(await page.evaluate(() => window.Vz2Timestamps), undefined, 'standalone editor does not need the list module');
        await page.locator('#segments-downloads summary').click();
        await page.locator('#segments-downloads select').selectOption(String(rehearsal.id));
        await page.getByRole('button', { name: 'Vybrat zobrazené', exact: true }).click();
        await page.getByRole('button', { name: 'Zařadit vybrané do fronty' }).click();
        await page.waitForFunction(() => Vz2Downloads.snapshot().length === 3 && Vz2Downloads.snapshot().every(t => t.state === 'complete'));
        assert.equal(await page.locator('#segments-audio').evaluate(a => a.paused), false);
        check(true, 'browser: timeline edits without list, preserves looping playback, and downloads entire rehearsal including mixer tracks');
        await page.locator('#segments-new-note').click();
        const point = page.locator('.vz2-annotation-editor');
        await point.locator('[name=label]').fill('Bod z časové osy');
        await setTime('start', '00:03.789');
        await point.locator('.annotation-save').click();
        await point.waitFor({ state: 'hidden' });
        const note = (await read(id)).annotations.find(i => i.label === 'Bod z časové osy');
        assert.equal(note.start_ms, 3789);
        await page.locator('[data-segment-id="' + note.id + '"]').click();
        await page.locator('#segments-edit').click();
        await point.locator('[name=label]').fill('Upravený bod z osy');
        await point.locator('.annotation-save').click();
        await point.waitFor({ state: 'hidden' });
        assert.equal((await read(id)).annotations.find(i => i.id === note.id).start_ms, 3789);
        assert.equal(await page.locator('#segments-selected-title').textContent(), 'Upravený bod z osy');
        assert.equal(await page.locator('#segments-finish').isVisible(), false);
        check(true, 'browser: timeline creates and edits point notes through standalone editor with exact milliseconds');

        assert.deepEqual(errors, []);
        await context.close();
    } finally { await browser.close(); }
};
